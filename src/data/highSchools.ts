/** 
 * 5대 권역별 고등학교 데이터 묶음
 */
export const HIGH_SCHOOLS_BY_REGION: Record<string, string[]> = {
  '서울': HIGH_SCHOOLS_DATA.filter(s => s.region === '서울').map(s => s.name),
  '경기/인천': HIGH_SCHOOLS_DATA.filter(s => ['경기', '인천'].includes(s.region)).map(s => s.name),
  '강원/충청': HIGH_SCHOOLS_DATA.filter(s => ['강원', '대전', '충남', '충북'].includes(s.region)).map(s => s.name),
  '전라/제주': HIGH_SCHOOLS_DATA.filter(s => ['광주', '전북', '전남', '제주'].includes(s.region)).map(s => s.name),
  '경상': HIGH_SCHOOLS_DATA.filter(s => ['부산', '대구', '울산', '경북', '경남'].includes(s.region)).map(s => s.name),
};

/** 모든 고등학교/클럽 이름 배열 반환 */
export function getAllHighSchools(): string[] {
  return HIGH_SCHOOLS_DATA.map(s => s.name);
}

/** 5대 권역명 목록 반환 */
export function getRegions(): string[] {
  return [...LEAGUE_ZONES];
}

/** 학교명으로 상세 데이터 조회 */
export function getHighSchoolDataByName(name: string): HighSchoolData | undefined {
  return HIGH_SCHOOLS_MAP.get(name);
}

/** ID로 상세 데이터 조회 */
export function getHighSchoolDataById(id: string): HighSchoolData | undefined {
  return HIGH_SCHOOLS_ID_MAP.get(id);
}

/** 티어별 고등학교 목록 조회 */
export function getHighSchoolsByTier(tier: HighSchoolData['tier']): HighSchoolData[] {
  return HIGH_SCHOOLS_DATA.filter(s => s.tier === tier);
}

/** 권역별 상세 고등학교 데이터 목록 조회 */
export function getHighSchoolDataListByZone(zone: string): HighSchoolData[] {
  const names = HIGH_SCHOOLS_BY_REGION[zone] || [];
  return names.map(name => HIGH_SCHOOLS_MAP.get(name)!).filter(Boolean);
}
