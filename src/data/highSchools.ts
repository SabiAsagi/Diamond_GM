HIGH_SCHOOLS_DATA.forEach(school => {
  const customEmblem = SCHOOL_EMBLEM_MAP[school.name];
  school.emblem = customEmblem || {
    primaryColor: '#1e3a8a',
    secondaryColor: '#f59e0b',
    textColor: '#ffffff',
    symbolText: school.name.slice(0, 2)
  };
  school.uniformPrimaryColor = school.emblem.primaryColor;
  school.uniformSecondaryColor = school.emblem.secondaryColor;

  const titles = SCHOOL_TITLES_MAP[school.name];
  if (titles) {
    school.tournamentTitles = titles;
  } else if (school.championships > 0) {
    school.tournamentTitles = {
      goldenLion: 0,
      blueDragon: 0,
      phoenix: 0,
      president: 0,
      others: school.championships
    };
  } else {
    school.tournamentTitles = {
      goldenLion: 0,
      blueDragon: 0,
      phoenix: 0,
      president: 0,
      others: 0
    };
  }
});

